import { sqliteTable, text, integer, real } from 'drizzle-orm/sqlite-core';

// ─── Bills ──────────────────────────────────────────────────────────────────
// Hybrid table: queryable top-level columns + full JSON blob in `data`.
// The `data` column stores the ENTIRE original bill object as stringified
// JSON, preserving the immutable snapshot invariant (profile, client,
// totals, options all frozen at invoice-creation time).
export const bills = sqliteTable('bills', {
  id:               text('id').primaryKey(),
  clientName:       text('client_name').notNull().default(''),
  invoiceNumber:    text('invoice_number').notNull().default(''),
  invoiceDate:      text('invoice_date').notNull().default(''),
  invoiceType:      text('invoice_type').notNull().default('tax-invoice'),
  currency:         text('currency').notNull().default('INR'),
  totalAmount:      real('total_amount').notNull().default(0),
  totalTaxAmount:   real('total_tax_amount').notNull().default(0),
  status:           text('status').notNull().default('unpaid'),
  paidAmount:       real('paid_amount').notNull().default(0),
  printedCount:     integer('printed_count').notNull().default(0),
  lastPrintedAt:    text('last_printed_at'),
  generatedFrom:    text('generated_from'),
  autoGenerated:    integer('auto_generated', { mode: 'boolean' }).notNull().default(false),
  autoGeneratedAt:  text('auto_generated_at'),
  // Soft-delete (trash)
  isTrashed:        integer('is_trashed', { mode: 'boolean' }).notNull().default(false),
  trashedAt:        text('trashed_at'),
  // Full JSON blob — the authoritative representation
  data:             text('data').notNull().default('{}'),
});

